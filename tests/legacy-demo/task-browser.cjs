/* Use installed Playwright: NODE_PATH=<node_modules path> node tests/task-browser.cjs */
const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const out = 'plans/reports/fr02';
const base = process.env.FR02_URL || 'http://127.0.0.1:4173/code.html';
(async () => {
  const browser = await chromium.launch({ headless: true, channel: 'chrome' });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1100 } });
  const errors = [], warnings = [], results = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('console', message => { if (message.type() === 'warning') warnings.push(message.text()); });
  const pass = name => { results.push(name); console.log(`PASS ${name}`); };
  const count = () => page.locator('#task-rows tr').count();
  const metric = async key => Number(await page.locator(`[data-metric="${key}"] strong`).textContent());
  const open = () => page.locator('[data-create-task]').first().click();
  const fill = async title => {
    await page.locator('#task-title').fill(title);
    await page.locator('#task-description').fill('Yêu cầu kiểm thử demo, không có dữ liệu cá nhân.');
    await page.locator('#task-assignee').selectOption('teacher-social');
    await page.locator('#task-due').fill('2026-10-25');
  };
  const saved = async () => { await page.waitForFunction(() => !document.getElementById('task-dialog').open); };
  try {
    await page.goto(base, { waitUntil: 'networkidle' });
    assert.equal(await count(), 4);
    assert.equal(await metric('total'), 4);
    assert.equal(await metric('active'), 3);
    assert.equal(await metric('pending'), 1);
    pass('baseline và metrics cùng nguồn dữ liệu');
    await open();
    await page.locator('#task-submit').click();
    for (const field of ['title', 'description', 'assigneeId', 'dueDate']) assert.ok(await page.locator(`[data-error="${field}"]`).textContent());
    assert.equal(await page.locator('#task-title').evaluate(el => el === document.activeElement), true);
    pass('validation tiếng Việt từng trường, focus lỗi đầu');
    await page.screenshot({ path: `${out}/desktop-validation.png`, fullPage: true });
    await page.locator('#task-cancel').click();
    assert.equal(await page.locator('[data-create-task]').first().evaluate(el => el === document.activeElement), true);
    await open();
    await page.keyboard.press('Shift+Tab');
    assert.equal(await page.locator('#task-dialog').evaluate(el => el.contains(document.activeElement)), true);
    await page.keyboard.press('Escape');
    assert.equal(await page.locator('#task-dialog').evaluate(el => el.open), false);
    pass('Hủy, Escape, focus ở dialog và trả focus về nút mở');
    await open(); await fill('Việc trường FR-02');
    await page.locator('[name="requiresApproval"]').check();
    await page.locator('[name="requiresEvidence"]').check();
    assert.equal(await page.locator('#task-scope').inputValue(), 'school');
    await page.locator('#task-submit').click();
    assert.equal(await page.locator('#task-submit').isDisabled(), true);
    assert.equal(await page.locator('#demo-user').isDisabled(), true);
    await page.locator('#task-form').evaluate(form => { form.requestSubmit(); form.requestSubmit(); });
    await saved();
    assert.equal(await count(), 5); assert.equal(await metric('total'), 5); assert.equal(await metric('active'), 4);
    assert.match(await page.locator('#task-notice').textContent(), /đọc lại thành công/);
    assert.match(await page.locator('#task-rows tr').filter({ hasText: 'Việc trường FR-02' }).textContent(), /Bắt buộc minh chứng/);
    pass('BGH giao trường, pending và gửi lặp chỉ một bản ghi; metrics/flags cập nhật');
    await page.locator('#demo-user').selectOption('teacher-social');
    assert.equal(await page.locator('[data-create-task]:visible').count(), 0);
    assert.equal(await page.locator('#task-rows tr').filter({ hasText: 'Việc trường FR-02' }).count(), 1);
    await page.locator('#demo-user').selectOption('teacher-science');
    assert.equal(await page.locator('#task-rows tr').filter({ hasText: 'Việc trường FR-02' }).count(), 0);
    pass('người nhận thấy việc mới, giáo viên khác không thấy, không có nút tạo');
    await page.locator('#demo-user').selectOption('head-social');
    await open();
    assert.equal(await page.locator('#task-scope').inputValue(), 'department');
    assert.deepEqual(await page.locator('#task-assignee option').evaluateAll(els => els.map(el => el.value)), ['', 'teacher-social']);
    await fill('Việc tổ KHXH FR-02'); await page.locator('#task-submit').click(); await saved();
    assert.equal(await page.locator('#task-rows tr').filter({ hasText: 'Việc tổ KHXH FR-02' }).count(), 1);
    await page.locator('#demo-user').selectOption('head-science');
    assert.equal(await page.locator('#task-rows tr').filter({ hasText: 'Việc tổ KHXH FR-02' }).count(), 0);
    pass('tổ trưởng chỉ chọn phạm vi và người nhận cùng tổ; tổ khác không thấy');
    await page.locator('#demo-user').selectOption('bgh');
    const before = await count();
    await page.locator('#demo-failure').check(); await open(); await fill('Thử lỗi và thử lại');
    await page.locator('#task-submit').click();
    await page.locator('[data-error="save"]').waitFor({ state: 'visible' });
    assert.equal(await page.locator('#task-title').inputValue(), 'Thử lỗi và thử lại');
    assert.equal(await count(), before);
    assert.equal(await page.locator('#task-submit').isEnabled(), true);
    assert.equal(await page.locator('#task-notice').textContent(), '');
    await page.locator('#task-submit').click(); await saved();
    assert.equal(await count(), before + 1);
    pass('lỗi trước ghi giữ form, không báo thành công, thử lại tạo đúng một việc');
    await open(); await fill('<img src=x onerror=alert(1)>');
    await page.locator('#task-submit').click(); await saved();
    assert.equal(await page.locator('#task-rows img').count(), 0);
    assert.equal(await page.locator('#task-rows tr').filter({ hasText: '<img src=x onerror=alert(1)>' }).count(), 1);
    pass('nội dung nhập được render như text, không thực thi HTML');
    await page.locator('#filter-urgent').click(); assert.equal(await count(), 1);
    await page.locator('#filter-overdue').click(); assert.equal(await count(), 7);
    await page.locator('#filter-all').click();
    await page.screenshot({ path: `${out}/desktop-list.png`, fullPage: true });
    for (const width of [320, 375, 768, 1440]) {
      await page.setViewportSize({ width, height: 900 });
      const overflow = await page.evaluate(() => document.documentElement.scrollWidth > innerWidth);
      assert.equal(overflow, false, `page overflow at ${width}`);
      if (width < 768) assert.deepEqual(await page.locator('#task-rows tr').first().locator('td').evaluateAll(cells => cells.slice(1).map(cell => cell.dataset.label)), ['Hạn chót (ngày)', 'Phạm vi', 'Trạng thái', 'Yêu cầu & Người giao']);
      await open(); await fill('Kiểm tra giao diện');
      const size = await page.locator('#task-dialog').evaluate(el => ({ width: el.getBoundingClientRect().width, overflow: el.scrollWidth > el.clientWidth }));
      assert.ok(size.width <= width); assert.equal(size.overflow, false);
      await page.locator('#task-submit').scrollIntoViewIfNeeded();
      await page.screenshot({ path: `${out}/form-${width}.png`, fullPage: false });
      await page.locator('#task-cancel').click();
    }
    pass('320/375/768/1440: trang và dialog không tràn ngang, nút có thể cuộn tới');
    await page.setViewportSize({ width: 375, height: 900 });
    await page.locator('#mobile-menu-toggle').click();
    await page.waitForFunction(() => document.body.classList.contains('menu-open'));
    assert.equal(await page.locator('body > .pl-64').evaluate(el => el.inert), true);
    await page.keyboard.press('Escape');
    assert.equal(await page.locator('body > .pl-64').evaluate(el => el.inert), false);
    pass('menu mobile hiện có vẫn mở, inert và đóng bằng Escape');
    await page.reload({ waitUntil: 'networkidle' });
    assert.equal(await count(), 4);
    pass('tải lại mất việc mới đúng cảnh báo demo');
    assert.deepEqual(errors, []);
    fs.writeFileSync(`${out}/browser-results.json`, JSON.stringify({ base, results, pageErrors: errors, warnings, date: new Date().toISOString() }, null, 2));
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
